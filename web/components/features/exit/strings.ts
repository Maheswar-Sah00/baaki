const TABLE: Record<UiLang, Record<ExitKey, string>> = { en, te, "hi-en": hiEn };

export type ExitT = (key: ExitKey, vars?: Record<string, string | number>) => string;

export function exitStrings(lang: UiLang): ExitT {
  const table = TABLE[lang] ?? en;
  return (key, vars) => {
    let s: string = table[key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}
