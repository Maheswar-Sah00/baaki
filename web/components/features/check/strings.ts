export const CHECK_STRINGS: Record<CheckLang, Dict> = { en, "hi-en": hiEn, te };

export type CheckT = (key: CheckKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: CheckLang): CheckT {
  const dict = CHECK_STRINGS[lang] ?? en;
  return (key, vars) => {
    let s = dict[key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

