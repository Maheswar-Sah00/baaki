const TABLES: Record<UiLang, Table> = { en, te, "hi-en": hiEn };

export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

export function translator(lang: UiLang): Translate {
  const table = TABLES[lang] ?? en;
  return (key, vars) => {
    let s = table[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

/** The consent text in all three languages at once (shown together on the voice screen). */
export function allLangs(key: StringKey): { lang: UiLang; text: string }[] {
  return (["te", "hi-en", "en"] as UiLang[]).map((l) => ({ lang: l, text: translator(l)(key) }));
}
