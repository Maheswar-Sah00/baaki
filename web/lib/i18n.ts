/** Any backend language code -> the UI language used for chrome. */
export function uiLangOf(lang: string | null | undefined): UiLang {
  if (!lang) return "en";
  if (lang.startsWith("te")) return "te";
  if (lang.startsWith("hi")) return "hi-en";
  return "en";
}

